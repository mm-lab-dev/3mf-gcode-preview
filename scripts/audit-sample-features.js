// Read-only input audit. Report names, classification rules, and actual paths
// separately so a comment-only tag is never reported as verified extrusion.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {createHash}=require('node:crypto');
const {inspectArchive}=require('../src/archive');
const {parseGcode,FEATURES,FEATURE_ALIASES}=require('../src/gcode');
const root=path.resolve(__dirname,'..');
const inputs=fs.readdirSync(path.join(root,'sample')).filter(name=>/^sample.*\.gcode(?:\.3mf)?$/i.test(name)).sort();
assert.ok(inputs.length,'No local G-code samples found');
const normalize=name=>name.trim().replace(/\s+/g,' ').toLowerCase();
const aliases=new Set(FEATURE_ALIASES.flat());
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const reports=[];
for(const filename of inputs) {
  const source=path.join(root,'sample',filename);
  const bytes=fs.readFileSync(source),sha256=hash(bytes);
  const archive=filename.endsWith('.3mf')?inspectArchive(bytes):{plates:[{name:filename,gcode:bytes.toString('utf8')}]};
  assert.ok(archive.plates.length,`${filename}: no G-code`);
  for(const plate of archive.plates) {
    const data=parseGcode(plate.gcode);
    assert.equal(data.sourceTypes.length,data.segmentCount);
    const counts=Array(data.sourceFeatures.length).fill(0);
    for(let i=0;i<data.segmentCount;i++) {
      const sourceId=data.sourceTypes[i];
      assert.ok(data.sourceFeatures[sourceId]);
      if(data.types[i]!==9) {
        assert.equal(data.types[i],data.sourceFeatures[sourceId].type);
        counts[sourceId]++;
      }
    }
    data.sourceFeatures.forEach((s,i)=>assert.equal(s.extrusionSegments,counts[i]));
    const features=data.sourceFeatures.map(s=>({...s,category:FEATURES[s.type],recognized:aliases.has(normalize(s.name)),extrusionVerified:s.extrusionSegments>0}));
    const generator=plate.gcode.match(/^;\s*(?:generated by .+|BambuStudio[^\r\n]*)/im)?.[0]||'Unknown';
    reports.push({filename,sha256,plate:plate.name,generator,layers:data.layers.length,segments:data.segmentCount,features,warnings:data.warnings});
    const unclassified=features.filter(s=>s.type===0&&s.extrusionVerified);
    console.log(`${filename}: ${data.layers.length} layers, ${data.segmentCount} segments; Other extrusion: ${unclassified.map(s=>`${s.name||'(no tag)'}=${s.extrusionSegments}`).join(', ')||'none'}`);
  }
  assert.equal(hash(fs.readFileSync(source)),sha256,'Input changed during audit');
}
const out=path.join(root,'test-results');fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'sample-feature-audit.json'),JSON.stringify({generatedAt:new Date().toISOString(),rules:FEATURES.map((name,id)=>({id,name,aliases:FEATURE_ALIASES[id]})),reports},null,2)+'\n');
console.log('Saved test-results/sample-feature-audit.json; input hashes unchanged.');
